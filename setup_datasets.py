#!/usr/bin/env python3
"""
setup_datasets.py

Extracts and prepares both PlantDoc and PlantVillage datasets:
1. archive (1).zip -> datasets/plantdoc/ (YOLOv8 object detection with 30 classes)
2. archive.zip     -> datasets/plantvillage/ (PlantVillage classification -> YOLO detection labels)
Generates:
- data_plantdoc.yaml
- data_plantvillage.yaml
"""

from __future__ import annotations

import os
import random
import shutil
import sys
import zipfile
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parent
DATASETS_DIR = ROOT / "datasets"
PLANTDOC_DIR = DATASETS_DIR / "plantdoc"
PLANTVILLAGE_DIR = DATASETS_DIR / "plantvillage"

ZIP_PLANTDOC = Path(r"C:\Users\VINOD SHARMA\Downloads\archive (1).zip")
ZIP_PLANTVILLAGE = Path(r"C:\Users\VINOD SHARMA\Downloads\archive.zip")

PLANTDOC_CLASSES = [
    "Apple Scab Leaf",
    "Apple leaf",
    "Apple rust leaf",
    "Bell_pepper leaf spot",
    "Bell_pepper leaf",
    "Blueberry leaf",
    "Cherry leaf",
    "Corn Gray leaf spot",
    "Corn leaf blight",
    "Corn rust leaf",
    "Peach leaf",
    "Potato leaf early blight",
    "Potato leaf late blight",
    "Potato leaf",
    "Raspberry leaf",
    "Soyabean leaf",
    "Soybean leaf",
    "Squash Powdery mildew leaf",
    "Strawberry leaf",
    "Tomato Early blight leaf",
    "Tomato Septoria leaf spot",
    "Tomato leaf bacterial spot",
    "Tomato leaf late blight",
    "Tomato leaf mosaic virus",
    "Tomato leaf yellow virus",
    "Tomato leaf",
    "Tomato mold leaf",
    "Tomato two spotted spider mites leaf",
    "grape leaf black rot",
    "grape leaf",
]


def extract_plantdoc() -> None:
    print("\n" + "=" * 60)
    print("[1/2] Processing PlantDoc Dataset (archive (1).zip)...")
    print("=" * 60)

    if not ZIP_PLANTDOC.exists():
        print(f"[ERROR] {ZIP_PLANTDOC} not found!")
        return

    PLANTDOC_DIR.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(ZIP_PLANTDOC, "r") as zf:
        members = zf.infolist()
        total = len(members)
        print(f"Extracting {total} items into {PLANTDOC_DIR}...")
        zf.extractall(PLANTDOC_DIR)

    dataset_path_str = str(PLANTDOC_DIR.resolve()).replace("\\", "/")

    yaml_content = f"""# PlantDoc YOLOv8 Object Detection Dataset Configuration
# Generated by setup_datasets.py

path: {dataset_path_str}
train: train/images
val: valid/images
test: test/images

nc: {len(PLANTDOC_CLASSES)}
names:
"""
    for idx, cname in enumerate(PLANTDOC_CLASSES):
        yaml_content += f"  {idx}: {cname}\n"

    (ROOT / "data_plantdoc.yaml").write_text(yaml_content, encoding="utf-8")
    (PLANTDOC_DIR / "data.yaml").write_text(yaml_content, encoding="utf-8")
    print("[OK] data_plantdoc.yaml created successfully!")

    train_imgs = list((PLANTDOC_DIR / "train" / "images").glob("*.*"))
    val_imgs = list((PLANTDOC_DIR / "valid" / "images").glob("*.*"))
    test_imgs = list((PLANTDOC_DIR / "test" / "images").glob("*.*"))
    print(f"[STATUS] PlantDoc verified: {len(train_imgs)} train, {len(val_imgs)} valid, {len(test_imgs)} test images.")


def extract_plantvillage() -> None:
    print("\n" + "=" * 60)
    print("[2/2] Processing PlantVillage Dataset (archive.zip)...")
    print("=" * 60)

    if not ZIP_PLANTVILLAGE.exists():
        print(f"[ERROR] {ZIP_PLANTVILLAGE} not found!")
        return

    PLANTVILLAGE_DIR.mkdir(parents=True, exist_ok=True)
    raw_images_dir = PLANTVILLAGE_DIR / "raw"
    raw_images_dir.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(ZIP_PLANTVILLAGE, "r") as zf:
        members = zf.infolist()
        total = len(members)
        print(f"Filtering duplicate hierarchies from {total} archive items...")

        extracted_count = 0
        for m in members:
            name = m.filename
            if not name.startswith("PlantVillage/") or name.endswith("/"):
                continue

            rel_path = name[len("PlantVillage/"):]
            if not rel_path or rel_path.startswith("svn-"):
                continue

            target_file = raw_images_dir / rel_path
            target_file.parent.mkdir(parents=True, exist_ok=True)
            with zf.open(m) as src, open(target_file, "wb") as dst:
                shutil.copyfileobj(src, dst)
            extracted_count += 1
            if extracted_count % 3000 == 0:
                print(f"  Extracted {extracted_count} images...")

        print(f"[OK] Extracted {extracted_count} unique images into {raw_images_dir}")

    classes = sorted([d.name for d in raw_images_dir.iterdir() if d.is_dir() and not d.name.startswith(".")])
    print(f"Discovered {len(classes)} classes: {classes}")

    print("Generating train/val splits and YOLO annotations...")
    train_img_dir = PLANTVILLAGE_DIR / "train" / "images"
    train_lbl_dir = PLANTVILLAGE_DIR / "train" / "labels"
    val_img_dir = PLANTVILLAGE_DIR / "val" / "images"
    val_lbl_dir = PLANTVILLAGE_DIR / "val" / "labels"

    for d in [train_img_dir, train_lbl_dir, val_img_dir, val_lbl_dir]:
        d.mkdir(parents=True, exist_ok=True)

    random.seed(42)
    class_to_id = {c: i for i, c in enumerate(classes)}
    total_train = 0
    total_val = 0

    for cname in classes:
        cdir = raw_images_dir / cname
        imgs = [f for f in cdir.iterdir() if f.is_file() and f.suffix.lower() in {".jpg", ".jpeg", ".png"}]
        random.shuffle(imgs)

        split_idx = int(len(imgs) * 0.8)
        train_imgs = imgs[:split_idx]
        val_imgs = imgs[split_idx:]

        cid = class_to_id[cname]
        bbox_line = f"{cid} 0.5 0.5 1.0 1.0\n"

        for f in train_imgs:
            dst_img = train_img_dir / f"{cname}_{f.name}"
            dst_lbl = train_lbl_dir / f"{cname}_{f.stem}.txt"
            if not dst_img.exists():
                shutil.copy2(f, dst_img)
            dst_lbl.write_text(bbox_line, encoding="utf-8")
            total_train += 1

        for f in val_imgs:
            dst_img = val_img_dir / f"{cname}_{f.name}"
            dst_lbl = val_lbl_dir / f"{cname}_{f.stem}.txt"
            if not dst_img.exists():
                shutil.copy2(f, dst_img)
            dst_lbl.write_text(bbox_line, encoding="utf-8")
            total_val += 1

    dataset_pv_path = str(PLANTVILLAGE_DIR.resolve()).replace("\\", "/")
    yaml_pv = f"""# PlantVillage YOLOv8 Detection Dataset Configuration
# Generated by setup_datasets.py

path: {dataset_pv_path}
train: train/images
val: val/images

nc: {len(classes)}
names:
"""
    for idx, cname in enumerate(classes):
        yaml_pv += f"  {idx}: {cname}\n"

    (ROOT / "data_plantvillage.yaml").write_text(yaml_pv, encoding="utf-8")
    (PLANTVILLAGE_DIR / "data.yaml").write_text(yaml_pv, encoding="utf-8")
    print(f"[OK] PlantVillage prepared: {total_train} train, {total_val} val images across {len(classes)} classes.")
    print("[OK] data_plantvillage.yaml created successfully!")


def main() -> None:
    print("[START] Starting PlantVision AI Dataset Setup...")
    extract_plantdoc()
    extract_plantvillage()
    print("\n" + "=" * 60)
    print("[SUCCESS] Dataset Setup Complete!")
    print("Available configs for training:")
    print("  1. data_plantdoc.yaml (Object Detection - 30 classes)")
    print("  2. data_plantvillage.yaml (PlantVillage - 15 classes)")
    print("=" * 60)


if __name__ == "__main__":
    main()
